// New York STATE solicitations -> live-ny-state.js (same shape as the NYC and SAM feeds).
//
// The conversion, filters and file writing are done. The one missing piece is the SOURCE:
// the NYS Contract Reporter has no known API, so getNotices() below is a stub until we hear
// back from them (support.nyscr@esd.ny.gov). Whatever the answer (API, permitted scraper,
// email digest), only getNotices() changes; it must return "raw notices" in this shape:
//
//   { id, title, agency, category, posted: "YYYY-MM-DD", due: "YYYY-MM-DD", dueTime: "3:00 PM ET",
//     url, description, value: number|null, region, requirements: [strings], restriction: string|null }
//
// Until a source exists, you can test the pipeline (or enter notices by hand) with a JSON file:
//   node fetch-ny-state.js --from-file my-notices.json     (an array of raw notices)

const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "live-ny-state.js");
const fileIdx = process.argv.indexOf("--from-file");
const FROM_FILE = fileIdx >= 0 ? process.argv[fileIdx + 1] : null;

// ---- Source (the part still to be decided) ----------------------------------------------
async function getNotices() {
  if (FROM_FILE) return JSON.parse(fs.readFileSync(FROM_FILE, "utf8"));
  throw new Error(
    "No State source configured yet. The NYS Contract Reporter has no known API; waiting for their reply.\n" +
    "To test the pipeline, run: node fetch-ny-state.js --from-file notices.json");
}

// ---- Clean-up shared in spirit with fetch-nyc.js ------------------------------------------
const stripHtml = (s) => String(s || "").replace(/<[^>]*>/g, " ").replace(/&nbsp;/g, " ").replace(/[\u0000-\u001f]/g, " ").replace(/\s+/g, " ").trim();

const SMALL = new Set("a an and as at but by for in of on or the to with".split(" "));
const ACRONYMS = new Set("NYS NYC SUNY CUNY DOT DEC OGS OTDA DOH DOCCS MTA IT HVAC II III IV".split(" "));
function tidyTitle(t) {
  if (!t || /[a-z]/.test(t) || !/[A-Z]{2}/.test(t)) return t;
  return t.toLowerCase().replace(/[a-z][a-z'’]*/g, (w, i) => {
    const up = w.toUpperCase();
    if (ACRONYMS.has(up) || !/[aeiouy]/.test(w)) return up;
    if (i > 0 && SMALL.has(w)) return w;
    return w[0].toUpperCase() + w.slice(1);
  });
}

const isDate = (s) => /^\d{4}-\d{2}-\d{2}$/.test(s || "");

function warnings(n) {
  const out = [];
  if (Number(n.due.slice(0, 4)) >= 2099) out.push("No real deadline (placeholder date)");
  if (isDate(n.posted) && Date.now() - new Date(n.posted).getTime() > 365 * 86400000) out.push("Posted over a year ago");
  return out;
}

function toRfq(n) {
  if (!n || !n.id || !isDate(n.due)) return null; // no deadline -> nothing to decide on
  // Only link to https pages (text comes from outside; never a javascript: or data: link).
  const url = typeof n.url === "string" && /^https:\/\//.test(n.url) ? n.url : null;
  if (!url) return null;
  const scope = stripHtml(n.description);
  const value = Number(n.value) > 0 ? Number(n.value) : null;
  return {
    id: "NYS-" + n.id,
    requires: Array.isArray(n.requires) ? n.requires : null, // null -> "Unclear" until restrictions are read
    scope: scope || "",
    shall: [],
    title: tidyTitle(stripHtml(n.title)) || "(untitled)",
    category: stripHtml(n.category) || "No data",
    posted: isDate(n.posted) ? n.posted : n.due,
    due: n.due,
    dueTime: n.dueTime || "No data",
    level: "State",
    agency: stripHtml(n.agency) || "NYS agency",
    value,
    rfqUrl: url,
    details: {
      region: stripHtml(n.region) || "New York State",
      requirements: (n.requirements || []).map(stripHtml).filter(Boolean),
      restriction: n.restriction || null,
      amended: !!n.amended,
      warnings: warnings(n)
    }
  };
}

(async () => {
  const today = new Date().toISOString().slice(0, 10);
  const raw = await getNotices();
  if (!Array.isArray(raw)) throw new Error("Source must return an array of notices.");
  const seen = new Set();
  const rfqs = raw.map(toRfq).filter((r) => {
    if (!r || r.due < today || seen.has(r.id)) return false; // drop invalid, past-due, duplicates
    seen.add(r.id);
    return true;
  });
  const meta = { source: "NYS Contract Reporter", fetchedAt: new Date().toISOString(), count: rfqs.length };
  fs.writeFileSync(OUT, "// GENERATED by fetch-ny-state.js - do not edit. Public NYS data.\n" +
    "(window.LIVE_SOURCES = window.LIVE_SOURCES || []).push({ meta: " + JSON.stringify(meta) + ", rfqs: " + JSON.stringify(rfqs, null, 1) + " });\n");
  console.log(`Wrote ${rfqs.length} State solicitations (of ${raw.length} given) to live-ny-state.js`);
})().catch((e) => { console.error(e.message); process.exit(1); });
